/**
 * Adopt the UIScene lifecycle on iOS.
 *
 * iOS 27 refuses to launch an app built with its SDK that has no scene
 * manifest (UIKit traps in _UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption,
 * so the app dies on open). Expo SDK 54's generated AppDelegate creates its
 * own window instead. This plugin:
 *   - adds UIApplicationSceneManifest (one window scene, SceneDelegate),
 *   - writes SceneDelegate.swift, which creates the window per scene and
 *     starts React Native in it (cold-start links and universal links are
 *     passed through launch options, later ones forwarded to the app delegate),
 *   - stops the AppDelegate from creating a window and keeps its launch options.
 */
const { IOSConfig, withDangerousMod, withInfoPlist, withXcodeProject } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const SCENE_DELEGATE = `import UIKit
import React

/// One window per scene (iOS 27 requires the scene lifecycle). Generated by
/// plugins/with-scene-lifecycle.js — edit the plugin, not this file.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(_ scene: UIScene, willConnectTo session: UISceneSession, options connectionOptions: UIScene.ConnectionOptions) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate,
          let factory = appDelegate.reactNativeFactory else { return }
    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // Links that opened the app arrive here instead of in launchOptions.
    var options = appDelegate.launchOptions ?? [:]
    if let url = connectionOptions.urlContexts.first?.url {
      options[.url] = url
    }
    if let activity = connectionOptions.userActivities.first {
      options[.userActivityDictionary] = [
        "UIApplicationLaunchOptionsUserActivityKey": activity,
        "UIApplicationLaunchOptionsUserActivityTypeKey": activity.activityType,
      ]
    }
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: options)
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }
    for context in URLContexts {
      _ = appDelegate.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }
    _ = appDelegate.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

const WINDOW_BLOCK = /#if os\(iOS\) \|\| os\(tvOS\)\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*factory\.startReactNative\(\s*withModuleName: "main",\s*in: window,\s*launchOptions: launchOptions\)\s*#endif/;

function patchAppDelegate(source) {
  if (source.includes('SceneDelegate.swift')) return source;
  if (!WINDOW_BLOCK.test(source)) {
    throw new Error('with-scene-lifecycle: AppDelegate.swift no longer matches the Expo SDK 54 template; update the plugin.');
  }
  return source
    .replace(WINDOW_BLOCK, '// The window is created per scene in SceneDelegate.swift (iOS 27 requires the\n    // scene lifecycle); React Native starts there with these launch options.\n    self.launchOptions = launchOptions')
    .replace('var reactNativeFactory: RCTReactNativeFactory?', 'var reactNativeFactory: RCTReactNativeFactory?\n  var launchOptions: [UIApplication.LaunchOptionsKey: Any]?');
}

module.exports = function withSceneLifecycle(config) {
  config = withInfoPlist(config, (c) => {
    c.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [{
          UISceneConfigurationName: 'Default Configuration',
          UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
        }],
      },
    };
    return c;
  });

  config = withXcodeProject(config, (c) => {
    const projectName = c.modRequest.projectName;
    const filepath = path.join(projectName, 'SceneDelegate.swift');
    if (!c.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project: c.modResults });
    }
    return c;
  });

  config = withDangerousMod(config, ['ios', async (c) => {
    const dir = path.join(c.modRequest.platformProjectRoot, c.modRequest.projectName);
    fs.writeFileSync(path.join(dir, 'SceneDelegate.swift'), SCENE_DELEGATE);
    const appDelegatePath = path.join(dir, 'AppDelegate.swift');
    fs.writeFileSync(appDelegatePath, patchAppDelegate(fs.readFileSync(appDelegatePath, 'utf8')));
    return c;
  }]);

  return config;
};
