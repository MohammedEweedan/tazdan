interface I18nState {
  locale: Locale;
  isHydrated: boolean;
  setLocale: (l: Locale) => void;
  cycle: () => void;
  hydrate: () => Promise<void>;
}

export const useI18n = create<I18nState>((set, get) => ({
  locale: 'en',
  isHydrated: false,
  setLocale: (l) => {
    set({ locale: l });
    if (I18nManager.isRTL) {
      try { I18nManager.allowRTL(false); I18nManager.forceRTL(false); } catch { /* noop */ }
    }
    AsyncStorage.setItem(KEY, l).catch(() => {});
  },
  cycle: () => {
    const order: Locale[] = ['en', 'ar', 'fr', 'es', 'de', 'nl', 'ru', 'zh'];
    const i = order.indexOf(get().locale);
    get().setLocale(order[(i + 1) % order.length]);
  },
  hydrate: async () => {
    try {
      const stored = (await AsyncStorage.getItem(KEY)) as Locale | null;
      if (stored && LOCALE_META[stored]) get().setLocale(stored);
    } catch { /* noop */ }
    set({ isHydrated: true });
  },
}));

/** Translation function — bound to the active locale store. */
export function useT() {
  const { locale, hydrate, isHydrated } = useI18n();
  useEffect(() => { if (!isHydrated) hydrate(); }, [isHydrated, hydrate]);
  return (key: string, vars?: Record<string, string | number>): string => {
    const raw = dict[locale][key] ?? dict.en[key] ?? key;
    if (!vars) return raw;
    return raw.replace(/\{\{(\w+)\}\}/g, (_, name) => String(vars[name] ?? `{{${name}}}`));
  };
}
