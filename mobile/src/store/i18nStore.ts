for (const locale of LOCALES) {
  if (locale === 'en') continue;
  for (const [key, value] of Object.entries(dict.en)) {
    if (dict[locale][key] == null) dict[locale][key] = value;
  }
}

const englishLiteralToKey = new Map<string, string>();
for (const [key, value] of Object.entries(dict.en)) {
  const normalized = value.trim();
  if (normalized && !englishLiteralToKey.has(normalized)) englishLiteralToKey.set(normalized, key);
}

function format(raw: string, vars?: Record<string, string | number>): string {
  if (!vars) return raw;
  return raw
    .replace(/\{\{(\w+)\}\}/g, (_, name) => String(vars[name] ?? `{{${name}}}`))
    .replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

export function translate(key: string, locale: Locale, vars?: Record<string, string | number>): string {
  return format(dict[locale][key] ?? dict.en[key] ?? key, vars);
}

export function translateLiteral(text: string | undefined | null, locale = useI18n.getState().locale): string | undefined | null {
  if (text == null) return text;
  const trimmed = text.trim();
  const key = englishLiteralToKey.get(trimmed);
  if (!key) return text;
  const translated = translate(key, locale);
  if (trimmed === text) return translated;
  return text.replace(trimmed, translated);
}

function patchImperativeI18n() {
  const alertAny = Alert as typeof Alert & { __tazdanI18nPatched?: boolean };
  if (!alertAny.__tazdanI18nPatched) {
    const originalAlert = Alert.alert.bind(Alert);
    Alert.alert = (title, message, buttons, options) => originalAlert(
      translateLiteral(title) ?? title,
      translateLiteral(message) ?? message,
      buttons?.map((button) => ({ ...button, text: translateLiteral(button.text) ?? button.text })),
      options,
    );
    alertAny.__tazdanI18nPatched = true;
  }

  if (Platform.OS === 'ios' && ActionSheetIOS) {
    const actionSheetAny = ActionSheetIOS as typeof ActionSheetIOS & { __tazdanI18nPatched?: boolean };
    if (!actionSheetAny.__tazdanI18nPatched) {
      const originalActionSheet = ActionSheetIOS.showActionSheetWithOptions.bind(ActionSheetIOS);
      ActionSheetIOS.showActionSheetWithOptions = (options, callback) => originalActionSheet(
        { ...options, options: options.options.map((label) => translateLiteral(label) ?? label) },
        callback,
      );
      actionSheetAny.__tazdanI18nPatched = true;
    }
  }
}

