#!/usr/bin/env node
/* Rebuilds src/content/appMedia.ts from what actually exists under
 * public/app/screens/<variant>/<id>.webp and public/app/video/<variant>/<id>.mp4,
 * keeping the captions/routes already in the manifest. Run after any capture:
 *   node scripts/gen-app-media.mjs */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "src/content/appMedia.ts");
const VARIANTS = ["en-dark", "ar-dark", "en-light"];
const prev = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
const meta = (id, field) => {
  const m = prev.match(new RegExp(`"${id}":\\s*\\{[^}]*?${field}:\\s*"([^"]*)"`));
  return m ? m[1] : null;
};
const scan = (kind, ext) => {
  const ids = new Map();
  for (const v of VARIANTS) {
    const dir = path.join(root, "public/app", kind, v);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir)) {
      if (!f.endsWith(ext)) continue;
      const id = f.slice(0, -ext.length);
      if (!ids.has(id)) ids.set(id, []);
      ids.get(id).push(v);
    }
  }
  return [...ids.entries()].sort(([a], [b]) => a.localeCompare(b));
};
const durationOf = (id, variant) => {
  try {
    const f = path.join(root, "public/app/video", variant, `${id}.mp4`);
    const out = execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f], { encoding: "utf8" });
    return Math.round(Number(out) * 10) / 10;
  } catch {
    const m = prev.match(new RegExp(`"${id}":\\s*\\{[^}]*?durationSec:\\s*([\\d.]+)`));
    return m ? Number(m[1]) : 8;
  }
};
const human = (id) => id.replace(/-/g, " ");
const screens = scan("screens", ".webp");
const videos = scan("video", ".mp4");
const gifs = scan("gif", ".gif");
const list = (vs) => `[${vs.map((v) => `'${v}'`).join(", ")}]`;
const ts = `// Generated by scripts/gen-app-media.mjs from the files under public/app/.
// Captures from the current Expo web build; the fixture account (a KYC-verified
// customer) uses illustrative data and the site labels it as such.
export type AppMediaVariant = 'en-dark' | 'ar-dark' | 'en-light';
export const APP_SCREENS: Record<string, { variants: AppMediaVariant[]; caption: string; route: string }> = {
${screens.map(([id, vs]) => `  "${id}": { variants: ${list(vs)}, caption: "${meta(id, "caption") ?? human(id)}", route: "${meta(id, "route") ?? ""}" },`).join("\n")}
};
export const APP_VIDEOS: Record<string, { variants: AppMediaVariant[]; durationSec: number; caption: string }> = {
${videos.map(([id, vs]) => `  "${id}": { variants: ${list(vs)}, durationSec: ${durationOf(id, vs[0])}, caption: "${meta(id, "caption") ?? human(id)}" },`).join("\n")}
};
/** Animated loops of page screens (public/app/gif/<variant>/<id>.gif). */
export const APP_GIFS: Record<string, AppMediaVariant[]> = {
${gifs.map(([id, vs]) => `  "${id}": ${list(vs)},`).join("\n")}
};
export const gifSrc = (id: string, v: AppMediaVariant = 'en-dark') => \`/app/gif/\${v}/\${id}.gif\`;
export const screenSrc = (id: string, v: AppMediaVariant = 'en-dark') => \`/app/screens/\${v}/\${id}.webp\`;
export const videoSrc = (id: string, v: AppMediaVariant = 'en-dark') => ({ mp4: \`/app/video/\${v}/\${id}.mp4\`, webm: \`/app/video/\${v}/\${id}.webm\`, poster: \`/app/video/\${v}/\${id}.jpg\` });
export const APP_MEDIA_NOTES = ['Screens from the current app build. Names and amounts are illustrative.'];
`;
fs.writeFileSync(out, ts);
console.log(`appMedia.ts: ${screens.length} screens, ${videos.length} videos, ${gifs.length} gifs`);
